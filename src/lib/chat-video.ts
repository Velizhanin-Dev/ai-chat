// ── Ссылки на ролики в сообщении чата ───────────────────────────────────────
//
// Чистый модуль (общий клиенту и серверу): только разбор текста, без сети.
//
// Зачем: человек кидает в чат ссылку на ролик и просит его разобрать. Сам текст
// ролика при этом в поле ввода попадать НЕ должен — расшифровку сервер добывает
// сам и кладёт в контекст модели (см. /api/chat). В сообщении остаётся ссылка,
// как её и написал человек.

const PATTERNS = [
  /youtu\.be\/([\w-]{6,20})/g,
  /youtube\.com\/watch\?[^\s]*[?&]?v=([\w-]{6,20})/g,
  /youtube\.com\/shorts\/([\w-]{6,20})/g,
  /youtube\.com\/live\/([\w-]{6,20})/g,
  /youtube\.com\/embed\/([\w-]{6,20})/g,
];

/**
 * id роликов из текста, по порядку появления, без повторов.
 *
 * ⚠️ Ограничение сверху обязательно: каждая расшифровка — это запрос к внешнему
 * сервису на десятки секунд. Человек, вставивший десять ссылок, иначе повесит
 * свой же ответ на несколько минут.
 */
export function extractVideoIds(text: string, limit = 2): string[] {
  const out: string[] = [];
  for (const re of PATTERNS) {
    // ⚠️ Регулярки глобальные и переиспользуются между вызовами — lastIndex
    // приходится сбрасывать, иначе второй вызов начнёт поиск с середины строки.
    re.lastIndex = 0;
    let m: RegExpExecArray | null;
    while ((m = re.exec(text)) !== null) {
      const id = m[1];
      if (id && !out.includes(id)) out.push(id);
      if (out.length >= limit) return out;
    }
  }
  return out;
}

/** Есть ли в тексте хоть одна ссылка на ролик. */
export function hasVideoLink(text: string): boolean {
  return extractVideoIds(text, 1).length > 0;
}
