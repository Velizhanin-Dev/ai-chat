// Пара «доминирующая+вторая» (в порядке) → архетип. Таблица результатов из ТЗ v6:
// прямые пары DI/ID/CS/SC/IS/SI, плюс три симметричные (Император DS/SD, Айрон Фист
// CD/DC → наш код DC, Илон Маск IC/CI) — оба порядка ведут к одному типу. Покрыты
// все 12 упорядоченных пар, поэтому разворот-фолбэк на практике не срабатывает.
const PAIR_TO_TYPE: Record<string, DiscType> = {
  DI: "DI", ID: "ID",
  CS: "CS", SC: "SC",
  IS: "IS", SI: "SI",
  DS: "DS", SD: "DS", // Император
  CD: "DC", DC: "DC", // Айрон Фист (наш код DC)
  IC: "IC", CI: "IC", // Илон Маск
};

// Разрешение равенства: сначала — кто из спорных букв набрал больше в «якорных»
// вопросах Q1/Q5/Q9 (0-индексы 0,4,8); если и там поровну — жёсткий приоритет
// C > D > I > S.
const TIEBREAK_QUESTIONS = [0, 4, 8];
const TIE_PRIORITY: DiscAxis[] = ["C", "D", "I", "S"];
// Перекрёстная тройка (реакция на критику/стресс): Q3/Q7/Q8 → 0-индексы 2,6,7.
// Три разные буквы среди них → тип «смешанный» (недостоверный).
const CROSS_CHECK_QUESTIONS = [2, 6, 7];

export interface DiscResult {
  pair: string; // напр. "DI"
  type: DiscType;
  scores: Record<DiscAxis, number>;
  isMixed: boolean;
}

// Основной скоринг теста. Вход — индексы выбранных вариантов (0=a … 4=e) по 10
// вопросам; ось каждого варианта берём из DISC_QUESTIONS (= «ключ» из ТЗ).
export function scoreDiscTest(answers: number[]): DiscResult {
  const letters: DiscAxis[] = answers.map(
    (oi, qi) => DISC_QUESTIONS[qi].options[oi].axis
  );

  const scores: Record<DiscAxis, number> = { D: 0, I: 0, S: 0, C: 0 };
  for (const l of letters) scores[l] += 1;

  // Счёт буквы среди якорных вопросов (для разрешения равенства).
  const anchor: Record<DiscAxis, number> = { D: 0, I: 0, S: 0, C: 0 };
  for (const qi of TIEBREAK_QUESTIONS) anchor[letters[qi]] += 1;

  const ranked = (["D", "I", "S", "C"] as DiscAxis[]).sort((a, b) => {
    if (scores[b] !== scores[a]) return scores[b] - scores[a];
    if (anchor[b] !== anchor[a]) return anchor[b] - anchor[a];
    return TIE_PRIORITY.indexOf(a) - TIE_PRIORITY.indexOf(b);
  });

  const pair = `${ranked[0]}${ranked[1]}`;
  const type =
    PAIR_TO_TYPE[pair] ?? PAIR_TO_TYPE[`${ranked[1]}${ranked[0]}`] ?? "IS";

  const isMixed =
    new Set(CROSS_CHECK_QUESTIONS.map((qi) => letters[qi])).size === 3;

  return { pair, type, scores, isMixed };
}

