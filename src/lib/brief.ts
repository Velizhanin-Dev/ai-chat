// ── Бриф клиента + карта харизмы (DISC) ────────────────────────────────────
// Чистый модуль без серверных зависимостей: используется и на клиенте (модалка
// брифа, скоринг теста), и на сервере (route.ts собирает блок для промпта,
// /api/auth/brief валидирует). Здесь живёт ВСЯ доменка брифа:
//   1) тип Brief и его поля;
//   2) короткий DISC-тест (вопросы) + скоринг → архетип;
//   3) карта 7 архетипов харизмы (форматы / что работает / что убивает) —
//      срисована с «карты харизмы» Велижанина;
//   4) сборка текстового блока для system-промпта.
//
// Из всего огромного маркетингового брифа агентства берём ТОЛЬКО то, что реально
// влияет на генерацию контента моделью (ниша, продукт, аудитория, экспертность,
// цель, опыт на камере, запреты). Остальное (ценники, рекламные кампании, база
// клиентов) модели не нужно — не тащим.

export type DiscType = "IC" | "CS" | "DI" | "DC" | "IS" | "SC" | "ID";

export type CameraExp = "pro" | "some" | "none" | "";

export interface Brief {
  channel: string; // канал / проект (название)
  niche: string; // чем занимается / сфера
  product: string; // что продвигает / продаёт через YouTube
  audience: string; // целевая аудитория
  expertise: string; // основная экспертность спикера
  goal: string; // зачем нужен YouTube (цель)
  cameraExp: CameraExp; // опыт на камере
  forbidden: string; // запретные темы (опц.)
  disc: DiscType | null; // результат DISC-теста (тип харизмы)
}

export const EMPTY_BRIEF: Brief = {
  channel: "",
  niche: "",
  product: "",
  audience: "",
  expertise: "",
  goal: "",
  cameraExp: "",
  forbidden: "",
  disc: null,
};

// Лимиты длины текстовых полей. Единый источник правды для:
//   1) обрезки на сервере (sanitizeBrief);
//   2) maxLength на инпутах в UI (BriefFlow) — чтобы санитайзинг был виден сразу.
export const BRIEF_LIMITS: Record<
  "channel" | "niche" | "product" | "audience" | "expertise" | "goal" | "forbidden",
  number
> = {
  channel: 200,
  niche: 400,
  product: 600,
  audience: 600,
  expertise: 600,
  goal: 400,
  forbidden: 400,
};

// Бриф считается пройденным, как только пройден DISC-тест. Все поля «о проекте»
// (канал/ниша/продукт/аудитория/экспертность/цель/камера/запреты) необязательны —
// их можно пропустить и в модалке, и на странице по QR. Обязателен только тип DISC.
export function isBriefComplete(b: Brief | null | undefined): boolean {
  return Boolean(b?.disc);
}

// Нормализация (и обрезка) пришедшего с клиента брифа — общий код для сервера.
export function sanitizeBrief(input: unknown): Brief {
  const o = (input ?? {}) as Record<string, unknown>;
  const str = (v: unknown, max: number) => String(v ?? "").trim().slice(0, max);
  const cam = String(o.cameraExp ?? "");
  const disc = String(o.disc ?? "") as DiscType;
  return {
    channel: str(o.channel, BRIEF_LIMITS.channel),
    niche: str(o.niche, BRIEF_LIMITS.niche),
    product: str(o.product, BRIEF_LIMITS.product),
    audience: str(o.audience, BRIEF_LIMITS.audience),
    expertise: str(o.expertise, BRIEF_LIMITS.expertise),
    goal: str(o.goal, BRIEF_LIMITS.goal),
    cameraExp: (["pro", "some", "none"].includes(cam) ? cam : "") as CameraExp,
    forbidden: str(o.forbidden, BRIEF_LIMITS.forbidden),
    disc: (DISC_PROFILES[disc] ? disc : null) as DiscType | null,
  };
}

