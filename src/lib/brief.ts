// ── Сборка блока для system-промпта ────────────────────────────────────────
// Вызывается на сервере (route.ts). Кладём только заполненные поля + карту
// архетипа спикера. Возвращаем "" если брифа фактически нет.
export function buildBriefBlock(b: Brief | null | undefined): string {
  if (!b) return "";

  const lines: string[] = [];
  const add = (label: string, v: string) => {
    if (v && v.trim()) lines.push(`- ${label}: ${v.trim()}`);
  };
  add("Канал / проект", b.channel);
  add("Ниша", b.niche);
  add("Что продвигает через YouTube", b.product);
  add("Целевая аудитория", b.audience);
  add("Экспертность спикера", b.expertise);
  add("Цель на YouTube", b.goal);
  if (b.cameraExp) add("Опыт на камере", CAMERA_LABEL[b.cameraExp]);
  add("⛔ Запретные темы (не предлагать!)", b.forbidden);

  const profile = b.disc ? DISC_PROFILES[b.disc] : null;

  if (lines.length === 0 && !profile) return "";

  const parts: string[] = [
    "# БРИФ КЛИЕНТА (с кем ты сейчас работаешь над контентом)",
  ];
  if (lines.length) parts.push(lines.join("\n"));

  if (profile) {
    parts.push(
      `## Тип харизмы спикера (карта харизмы: «${profile.nick}»)\n` +
        `- Характер: ${profile.character}\n` +
        `- Суперсила — на ней и строй его контент: ${profile.superpower}\n` +
        `- Подходящие форматы: ${profile.formats}\n` +
        `- Что заводит и работает в кадре: ${profile.works}\n` +
        `- Слабые места — учитывай и подстраховывай: ${profile.weakness}\n` +
        `- Что его убивает — НЕ предлагать и не делать: ${profile.kills}`
    );

    parts.push(
      "Как использовать тип харизмы:\n" +
        "- Всегда подбирай форматы, темы и подачу под его тип и нишу: опирайся на " +
        "суперсилу и «что работает», обходи «что убивает» и слабые места, уважай " +
        "запретные темы.\n" +
        "- Когда выдаёшь сценарий, хук, контент-план или совет по съёмке — добавляй " +
        "конкретный практический разбор «как тебе действовать в кадре именно под " +
        "твой характер»: на что опереться (суперсила), что усилить, чего избегать, " +
        "как держаться перед камерой, чтобы раскрыть себя. Пиши это как личный совет " +
        "(«тебе в кадре зайдёт…», «тебе будет тяжело вот тут — поэтому давай так»), " +
        "простыми словами и по делу.\n" +
        "- Молчи про механику: НЕ пересказывай сам бриф, НЕ сыпь теорией (DISC, " +
        "название архетипа, буквы D/I/S/C) — если пользователь прямо не спросил " +
        "«почему так». Термины — внутрь, польза — наружу."
    );
  } else {
    parts.push(
      "Учитывай это молча: подстраивай примеры, нишу и подачу под пользователя. Не " +
        "пересказывай ему этот бриф и не упоминай, что у тебя есть «карточка» — " +
        "просто говори по делу с учётом контекста."
    );
  }

  return parts.join("\n\n");
}
