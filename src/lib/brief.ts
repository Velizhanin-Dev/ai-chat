// ── Бриф клиента + карта харизмы (DISC) ────────────────────────────────────
// Чистый модуль без серверных зависимостей: используется и на клиенте (модалка
// брифа, скоринг теста), и на сервере (route.ts собирает блок для промпта,
// /api/auth/brief валидирует). Здесь живёт ВСЯ доменка брифа:
//   1) тип Brief и его поля;
//   2) короткий DISC-тест (вопросы) + скоринг → архетип;
//   3) карта 7 архетипов харизмы (форматы / что работает / что убивает) —
//      срисована с «карты харизмы» Велижанина;
//   4) сборка текстового блока для system-промпта.
//
// Из всего огромного маркетингового брифа агентства берём ТОЛЬКО то, что реально
// влияет на генерацию контента моделью (ниша, продукт, аудитория, экспертность,
// цель, опыт на камере, запреты). Остальное (ценники, рекламные кампании, база
// клиентов) модели не нужно — не тащим.

export type DiscType =
  | "IC"
  | "CS"
  | "DI"
  | "DC"
  | "IS"
  | "SC"
  | "ID"
  | "SI"
  | "DS";

export type CameraExp = "pro" | "some" | "none" | "";

export interface Brief {
  channel: string; // канал / проект (название)
  niche: string; // чем занимается / сфера
  product: string; // что продвигает / продаёт через YouTube
  audience: string; // целевая аудитория
  expertise: string; // основная экспертность спикера
  goal: string; // зачем нужен YouTube (цель)
  cameraExp: CameraExp; // опыт на камере
  forbidden: string; // запретные темы (опц.)
  disc: DiscType | null; // результат DISC-теста (тип харизмы)
  isMixed: boolean; // тип «смешанный» (недостоверная перекрёстная тройка Q3/Q7/Q8)
}

