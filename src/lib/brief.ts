// Топ-2 оси (по порядку) → архетип. Покрываем все 12 упорядоченных пар; пары,
// которых нет в «карте харизмы», сводим к ближайшему архетипу по первичной оси.
const PAIR_TO_TYPE: Record<string, DiscType> = {
  DI: "DI", DC: "DC", DS: "DC",
  ID: "ID", IC: "IC", IS: "IS",
  SC: "SC", SI: "IS", SD: "SC",
  CS: "CS", CD: "DC", CI: "IC",
};

const AXIS_ORDER: DiscAxis[] = ["D", "I", "S", "C"];

// Скоринг: массив выбранных осей (по одной на вопрос) → тип харизмы.
export function scoreDisc(answers: DiscAxis[]): DiscType {
  const score: Record<DiscAxis, number> = { D: 0, I: 0, S: 0, C: 0 };
  for (const a of answers) score[a] += 1;
  // Сортируем оси по убыванию балла; при равенстве — стабильно по AXIS_ORDER.
  const ranked = [...AXIS_ORDER].sort((a, b) => score[b] - score[a]);
  const [first, second] = ranked;
  return PAIR_TO_TYPE[`${first}${second}`] ?? "IS";
}

