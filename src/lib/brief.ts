// ── Сборка блока для system-промпта ────────────────────────────────────────
// Вызывается на сервере (route.ts). Кладём только заполненные поля + карту
// архетипа спикера. Возвращаем "" если брифа фактически нет.
export function buildBriefBlock(b: Brief | null | undefined): string {
  if (!b) return "";

  const lines: string[] = [];
  const add = (label: string, v: string) => {
    if (v && v.trim()) lines.push(`- ${label}: ${v.trim()}`);
  };
  add("Канал / проект", b.channel);
  add("Ниша", b.niche);
  add("Что продвигает через YouTube", b.product);
  add("Целевая аудитория", b.audience);
  add("Экспертность спикера", b.expertise);
  add("Цель на YouTube", b.goal);
  if (b.cameraExp) add("Опыт на камере", CAMERA_LABEL[b.cameraExp]);
  add("⛔ Запретные темы (не предлагать!)", b.forbidden);

  const profile = b.disc ? DISC_PROFILES[b.disc] : null;

  if (lines.length === 0 && !profile) return "";

  const parts: string[] = [
    "# БРИФ КЛИЕНТА (с кем ты сейчас работаешь над контентом)",
  ];
  if (lines.length) parts.push(lines.join("\n"));

  if (profile) {
    parts.push(
      `## Тип харизмы спикера по DISC: «${profile.nick}» (${profile.code})\n` +
        `- Характер: ${profile.character}\n` +
        `- Подходящие форматы: ${profile.formats}\n` +
        `- Что его заводит и работает: ${profile.works}\n` +
        `- Что его убивает — НЕ предлагать: ${profile.kills}`
    );
  }

  parts.push(
    "Учитывай это молча: подбирай форматы и подачу под его тип харизмы и нишу, " +
      "опирайся на «что работает», обходи «что убивает» и запретные темы. Не " +
      "пересказывай ему этот бриф и не упоминай, что у тебя есть «карточка» или " +
      "«DISC-тип» — просто говори по делу с учётом контекста."
  );

  return parts.join("\n\n");
}
