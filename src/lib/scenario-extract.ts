// Выделение «чистого» сценария из ответа ассистента — чистый модуль (клиент/сервер).
//
// Зачем: ответ в чате почти всегда обёрнут в живую речь — вводная фраза сверху и
// предложение следующего шага снизу («Продолжаю?», «Скинуть ещё?»). Для чтения это
// хорошо, а вот когда сценарий уносят в продакшн — в Google Docs, суфлёр, монтажёру —
// комментарии мешают. Отсюда отдельная кнопка «Скопировать сценарий»: она отдаёт
// только сам артефакт.
//
// ⚠️ Это ЭВРИСТИКА, а не разбор формата: модель пишет свободным markdown, жёсткой
// разметки «вот тут сценарий» у нас нет. Поэтому правило простое и предсказуемое:
// режем только то, в чём уверены (обрамляющая речь), а при сомнении оставляем текст
// как есть. Лучше отдать лишний абзац, чем срезать кусок сценария.

// Ответ похож на сценарий? Кнопку показываем только тогда — на «привет» и коротких
// разборах она была бы шумом.
export function looksLikeScenario(md: string): boolean {
  // 300 символов: короче — это реплика в диалоге, а не артефакт. Проверено на
  // компактном сценарии в 386 знаков (порог 400 его отсекал).
  if (md.length < 300) return false;
  const text = md.toLowerCase();
  // Маркеры сценарной структуры из методики. Одного мало — берём от двух, иначе
  // под кнопку попадёт любой разбор, где всплыло слово «хук».
  const markers = [
    "хук",
    "опенинг",
    "заход",
    "усугубление",
    "проброс",
    "cta",
    "призыв",
    "финал",
    "кульминаци",
    "блок",
    "сцена",
    "в кадр",
    "закадр",
  ];
  const hits = markers.filter((m) => text.includes(m)).length;
  // Заголовки или список — признак структуры, а не сплошного рассуждения.
  const structured = /^#{1,4}\s/m.test(md) || /^\s*[-*]\s/m.test(md) || /^\s*\d+[.)]\s/m.test(md);
  return hits >= 2 && structured;
}

// Строка — обрамляющая речь ассистента, а не часть сценария?
// Ловим два типичных хвоста: вопрос-предложение следующего шага и короткую
// подводку вида «Держи», «Вот сценарий», «Собрал под твою нишу».
const TAIL_OFFER =
  /^(хочешь|продолжаю|продолжить|скинуть|скину|давай|нужно ли|если нужно|могу |готов |ещё |если ок|как тебе|что скажешь|погнали)/i;
const HEAD_LEADIN =
  /^(держи|вот |лови|собрал|сделал|накидал|погнали|окей|ок[,.]|хорошо[,.]|понял|сейчас)/i;

function isOffer(line: string): boolean {
  const t = line.trim();
  if (!t) return false;
  // Длинную строку не трогаем — это уже содержание, даже если начинается с «Могу».
  if (t.length > 160) return false;
  return TAIL_OFFER.test(t) || (t.endsWith("?") && t.length < 120);
}

function isLeadIn(line: string): boolean {
  const t = line.trim();
  if (!t) return false;
  if (t.length > 160) return false;
  return HEAD_LEADIN.test(t);
}

// Убрать обрамляющую речь. Возвращает исходный markdown, если резать нечего.
export function extractScenario(md: string): string {
  const lines = md.replace(/\r\n/g, "\n").split("\n");

  let start = 0;
  let end = lines.length;

  // Сверху: снимаем подводку ТОЛЬКО если ниже действительно есть структура —
  // иначе рискуем срезать первую строку самого сценария.
  const firstStructural = lines.findIndex(
    (l) => /^#{1,4}\s/.test(l) || /^\s*[-*]\s/.test(l) || /^\s*\d+[.)]\s/.test(l)
  );
  if (firstStructural > 0) {
    while (start < firstStructural && (!lines[start].trim() || isLeadIn(lines[start]))) {
      start += 1;
    }
    // Строку, которая не подводка, не трогаем — откатываемся.
    if (start > 0 && lines[start - 1]?.trim() && !isLeadIn(lines[start - 1])) {
      // ничего: start уже стоит после подводок
    }
  }

  // Снизу: снимаем хвостовые предложения-приглашения и пустые строки.
  while (end > start) {
    const line = lines[end - 1];
    if (!line.trim()) {
      end -= 1;
      continue;
    }
    // ⚠️ Только «голый» абзац: заголовок, пункт списка или цитату не режем, даже
    // если они кончаются вопросом — вопрос вполне может быть частью сценария
    // (например, пункт «10 вопросов» или реплика в кадр).
    const plain = !/^\s*([-*>]|\d+[.)]|#{1,4})\s/.test(line);
    if (plain && isOffer(line)) {
      end -= 1;
      continue;
    }
    break;
  }

  const out = lines.slice(start, end).join("\n").trim();
  // Подстраховка: если эвристика съела больше половины — значит она ошиблась,
  // отдаём оригинал.
  return out.length >= md.trim().length * 0.5 ? out : md.trim();
}

// Имя файла для скачивания: первый заголовок или первая строка сценария.
export function scenarioFileName(md: string): string {
  const head =
    md.match(/^#{1,4}\s+(.+)$/m)?.[1] ??
    md.split("\n").find((l) => l.trim().length > 3) ??
    "сценарий";
  const clean = head
    .replace(/[*_`>#|]/g, "")
    .replace(/[\\/:*?"<>]/g, "")
    .trim()
    .slice(0, 60);
  return `${clean || "сценарий"}.txt`;
}
