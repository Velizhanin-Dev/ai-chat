// ── О чём спрашивают зрители: чистый модуль (клиент/сервер) ──────────────────
//
// Зачем: главный дефект идей — «средние по интернету» темы (Антипаттерн №15).
// Лечится он фактурой, а самая честная фактура про боли аудитории лежит прямо под
// роликами канала: зрители сами пишут, чего им не хватает и что непонятно. Это не
// выдумка модели и не строка из брифа, а формулировки живых людей.
//
// ⚠️ Считаем ЧАСТОТУ тем, а не выбираем «самый залайканный коммент»: один
// эмоциональный вопрос под удачным роликом — случайность, десять похожих под
// разными роликами — запрос аудитории, из которого получается ролик.

export interface AudienceQuestion {
  /** Текст вопроса как его написал зритель (обрезанный). */
  text: string;
  likes: number;
  videoId: string;
  videoTitle: string;
}

export interface QuestionTopic {
  /** Слово-ядро темы (по нему группировали). */
  keyword: string;
  /** Сколько вопросов про это. */
  count: number;
  /** Примеры формулировок — их и показываем человеку. */
  examples: AudienceQuestion[];
}

export interface AudienceQuestionsResult {
  topics: QuestionTopic[];
  /** Всего вопросов найдено (до группировки). */
  total: number;
  /** По скольким роликам смотрели комментарии. */
  videosScanned: number;
  fetchedAt: string;
}

// Слова, по которым узнаём вопрос без знака вопроса («подскажите как…»).
const QUESTION_WORDS = [
  "как",
  "почему",
  "зачем",
  "что делать",
  "какой",
  "какая",
  "какие",
  "сколько",
  "где",
  "когда",
  "можно ли",
  "стоит ли",
  "подскажите",
  "посоветуйте",
  "а если",
];

// Мусор, который в темы не идёт: благодарности, приветствия, оценка ролика.
// ⚠️ Именно «спасибо за видео» и «класс» составляют большую часть комментариев,
// и без этого фильтра они забивают весь список.
const NOISE = [
  "спасибо",
  "благодар",
  "класс",
  "супер",
  "лайк",
  "подписал",
  "красав",
  "молодец",
  "огонь",
  "топ",
  "жду продолжения",
];

// Служебные слова: в ядро темы не годятся.
const STOP = new Set([
  "как", "что", "это", "так", "вот", "там", "тут", "все", "всё", "если", "или", "для", "про",
  "уже", "ещё", "еще", "надо", "нужно", "можно", "быть", "есть", "него", "нее", "неё", "они",
  "вас", "нас", "мне", "меня", "тебя", "себя", "который", "которая", "которые", "почему",
  "зачем", "когда", "где", "сколько", "какой", "какая", "какие", "будет", "было", "очень",
  "просто", "тоже", "может", "можете", "подскажите", "посоветуйте", "здравствуйте", "привет",
  "видео", "ролик", "канал", "спасибо", "автор",
]);

function normalize(text: string): string {
  return text.replace(/\s+/g, " ").trim();
}

/** Похоже ли это на вопрос зрителя, а не на «спасибо, класс». */
export function looksLikeQuestion(raw: string): boolean {
  const text = normalize(raw).toLowerCase();
  if (text.length < 12 || text.length > 400) return false;

  // Благодарности и оценки отсекаем, даже если там есть знак вопроса.
  if (NOISE.some((n) => text.includes(n)) && !text.includes("?")) return false;

  if (text.includes("?")) return true;
  return QUESTION_WORDS.some((w) => text.startsWith(w) || text.includes(` ${w} `));
}

function words(text: string): string[] {
  // ⚠️ Класс символов перечислен буквами, а НЕ через \p{L}/u: текущий target сборки
  // такие регулярки не принимает (те же грабли, что в competitors.ts).
  return normalize(text)
    .toLowerCase()
    .split(/[^0-9a-zа-яё]+/)
    .filter((w) => w.length >= 4 && !STOP.has(w));
}

/**
 * Группировка вопросов по слову-ядру.
 *
 * ⚠️ Никакой лемматизации: «моды» и «модов» останутся разными ядрами. Это
 * осознанно — словарь форм русского языка мы тут не потянем, а для «о чём чаще
 * всего спрашивают» хватает и сырой частоты: обе формы всё равно всплывут рядом.
 */
export function groupQuestions(
  questions: AudienceQuestion[],
  limit = 8
): QuestionTopic[] {
  const byKeyword = new Map<string, QuestionTopic>();

  for (const q of questions) {
    // Каждый вопрос попадает максимум в три темы — по самым длинным словам:
    // длинное слово почти всегда содержательнее короткого.
    const keys = Array.from(new Set(words(q.text)))
      .sort((a, b) => b.length - a.length)
      .slice(0, 3);

    for (const key of keys) {
      const hit = byKeyword.get(key);
      if (hit) {
        hit.count += 1;
        if (hit.examples.length < 4) hit.examples.push(q);
      } else {
        byKeyword.set(key, { keyword: key, count: 1, examples: [q] });
      }
    }
  }

  return Array.from(byKeyword.values())
    .filter((t) => t.count >= 2) // одиночный вопрос — ещё не тема
    .sort((a, b) => b.count - a.count || b.examples[0].likes - a.examples[0].likes)
    .slice(0, limit);
}

/** Запрос ассистенту: темы роликов из реальных вопросов аудитории. */
export function questionsPrompt(result: AudienceQuestionsResult): string {
  const lines = result.topics.slice(0, 6).map((t) => {
    const examples = t.examples
      .slice(0, 3)
      .map((e) => `«${e.text.slice(0, 160)}»`)
      .join("; ");
    return `- ${t.keyword} (спрашивают ${t.count} раз): ${examples}`;
  });

  return [
    "Вот о чём реально спрашивают зрители под моими роликами — это их слова, не мои догадки:",
    "",
    ...lines,
    "",
    "Собери из этого 5 тем для роликов: на каждую — название по ВИСП, текст на превью и одну строку, почему именно эта боль зацепит. Бери формулировки зрителей как основу боли ЦА, а не общие рассуждения про нишу.",
  ].join("\n");
}
