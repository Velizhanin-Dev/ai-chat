// Справочник параметров органического продвижения — общий для клиента и сервера
// (UI рисует по нему круг и подписи, промпт разбора берёт отсюда нормы и способ
// измерения). Чистый модуль: без prisma и серверных импортов.
//
// ⚠️ Нормы здесь — ТОЛЬКО те, что явно есть в базе знаний (правило одного процента,
// CTR ~5/10%, среднее время >7 минут, коридор шортса). Там, где методика жёсткой
// цифры не даёт, norm пустой — оценку ставит модель, у которой база в контексте.
// Не дописывай сюда придуманные пороги.

import type { DiagnoseKind, LongParamKey, ParamKey, ShortsParamKey } from "./youtube-types";

export interface ParamSpec {
  key: ParamKey;
  // Короткая подпись в секторе круга (влезает в 2 строки).
  short: string;
  // Полное название параметра.
  label: string;
  // Что это и почему важно — в панели деталей.
  about: string;
  // Норма по методике; пустая строка = жёсткой цифры в методике нет.
  norm: string;
  // Единица значения: "%" | "sec" | "".
  unit: "%" | "sec" | "";
  // Как считаем из данных YouTube (идёт и в промпт — чтобы модель не выдумывала
  // источник цифры и честно говорила, где это лишь прокси).
  measure: string;
}

