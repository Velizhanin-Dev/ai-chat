import type { QuestionTopic } from "./audience-questions";
import {
  compareToUsual,
  engagementRate,
  median,
  retentionPercent,
  type IgReel,
  type IgSnapshot,
  type Verdict,
} from "./instagram-types";

// ── Instagram → system-блок для промпта (чистый модуль) ─────────────────────
//
// Аналог buildChannelBlock (system.ts) для Instagram-проекта. Отдельным модулем,
// а не веткой внутри buildChannelBlock: у площадок РАЗНЫЙ набор цифр, и общий
// код с ветвлениями «если инстаграм, то не пиши про удержание» читался бы хуже,
// чем два независимых блока.
//
// ⚠️ Шапка прямо перечисляет, чего у модели НЕТ (кривой удержания, источников
// просмотров, демографии по рилсу, CTR и превью в YouTube-смысле). Без этого она
// либо обещает «полную аналитику», которой нет, либо рассуждает про удержание,
// которого не видела, — класс ошибок Антипаттерна №9. И отдельно — что советы
// про 16:9-превью, теги и SEO YouTube сюда не переносятся: у рилсов упаковка —
// вертикальная обложка, первые 3 секунды и подпись.

/** Сколько рилсов перечисляем построчно: по 30 рилсов блок разбухает в ~2k токенов. */
const MAX_REELS_IN_PROMPT = 12;

const numFmt = new Intl.NumberFormat("ru-RU");
function n(v: number | null): string {
  return v == null ? "—" : numFmt.format(Math.round(v));
}
function pct(v: number | null): string {
  return v == null ? "—" : `${v.toFixed(1).replace(".", ",")}%`;
}
function sec(v: number | null): string {
  return v == null ? "—" : `${v.toFixed(1).replace(".", ",")} с`;
}

const VERDICT_WORD: Record<Verdict, string> = {
  better: "выше обычного",
  usual: "как обычно",
  worse: "ниже обычного",
};

/** Подпись рилса для строки: первая строка caption, без переносов, до 70 знаков. */
function reelLabel(r: IgReel): string {
  const first = (r.caption || "").split(/\r?\n/)[0].trim();
  if (!first) return "(без подписи)";
  return first.length > 70 ? `${first.slice(0, 67)}…` : first;
}

/** Медиана только по непустым значениям; null, если считать не по чему. */
function medianOf(xs: Array<number | null>): number | null {
  const vals = xs.filter((x): x is number => x != null && Number.isFinite(x));
  return vals.length ? median(vals) : null;
}

/**
 * System-блок с живыми данными Instagram-аккаунта проекта.
 *
 * Медианы по рилсам периода, потом рилсы построчно (по просмотрам вниз) с
 * вердиктом «выше/ниже обычного» — тем же compareToUsual, что в дашборде:
 * база для сравнения — свои же рилсы, а не рыночная норма.
 */
export function buildInstagramBlock(s: IgSnapshot, questions: QuestionTopic[] = []): string {
  const a = s.account;
  const reels = s.reels;
  const lines: string[] = [
    "# ЖИВЫЕ ДАННЫЕ INSTAGRAM-АККАУНТА ПОЛЬЗОВАТЕЛЯ (проект про Instagram, аккаунт подключён)",
    "Ниже — свежая статистика его рилсов (обновляется периодически, может чуть отставать). Когда вопрос про его аккаунт — рост, охваты, какие рилсы зашли, что снимать дальше — разбирай ПРЕДМЕТНО по этим цифрам, в моём голосе, методику молча. Ссылайся на конкретику по делу (какой рилс пролистывают, где досмотр держится), но НЕ вываливай всю статистику простынёй без запроса. Если вопрос не про его аккаунт — просто держи данные в уме. Не хватает цифр — так и скажи.",
    "⚠️ Это Instagram, а НЕ YouTube. Тут нет CTR и показов превью, нет горизонтальной обложки, тегов и SEO-описания в ютубовском смысле — советы про них сюда не переносятся. Упаковка рилса — это ХУК в первые 3 секунды (его меряет доля пропусков), вертикальная обложка под сетку профиля, подпись и текст на экране. Формулы названий по ВИСП работают и здесь — как первая строка подписи и как текст на экране.",
    "⚠️ Чего у тебя тут НЕТ и не будет: кривой удержания по секундам (только среднее время просмотра), источников просмотров (лента / рекомендации / профиль), демографии по конкретному рилсу, динамики просмотров рилса по дням. API этого не отдаёт. Не рассуждай об этих цифрах, будто видел их, и не выдумывай. Пустые метрики («—») — это НЕ ноль: Meta не отдаёт цифры, пока у рилса мало охвата.",
    "Когда уместно (разбираешь его цифры, он хочет копнуть глубже) — одной фразой напомни, что подробности по каждому рилсу он смотрит в приложении в разделе «Канал». Не в каждом ответе.",
    "",
    `Аккаунт: @${a.username}${a.name && a.name !== a.username ? ` (${a.name})` : ""} — ${n(a.followers)} подписчиков, ${n(a.mediaCount)} публикаций всего.`,
  ];

  if (reels.length === 0) {
    lines.push(
      `За последние ${s.periodDays} дней рилсов не выходило (или они ещё не попали в статистику). Разбирать нечего — говори об этом честно и работай от брифа.`
    );
    return lines.join("\n");
  }

  const views = reels.map((r) => r.views);
  const reach = reels.map((r) => r.reach);
  const skip = reels.map((r) => r.skipRate);
  const watch = reels.map((r) => r.avgWatchTime);
  const eng = reels.map((r) => engagementRate(r));

  lines.push(
    `За ${s.periodDays} дней вышло рилсов: ${reels.length}. Медианы по ним: просмотры ${n(medianOf(views))}, охват ${n(medianOf(reach))}, пролистали в первые 3 секунды ${pct(medianOf(skip))}, среднее время просмотра ${sec(medianOf(watch))}, вовлечение (лайки+комменты+сохранения+репосты от охвата) ${pct(medianOf(eng))}.`,
    "Сравнивай рилс с медианой ЕГО ЖЕ аккаунта, а не с абстрактной нормой: у каждого аккаунта своя база."
  );

  // Строки по рилсам: по просмотрам вниз, без просмотров — в конец.
  const sorted = [...reels].sort((x, y) => (y.views ?? -1) - (x.views ?? -1));
  const shown = sorted.slice(0, MAX_REELS_IN_PROMPT);
  const viewVals = views.filter((v): v is number => v != null);

  lines.push(
    "",
    `Рилсы (подпись — просмотры, охват, пролистали за 3 с, среднее время просмотра, вовлечение)${reels.length > shown.length ? `, верхние ${shown.length} из ${reels.length}` : ""}:`
  );
  for (const r of shown) {
    const others = viewVals.filter((v) => v !== r.views);
    const verdict = compareToUsual(r.views, others);
    const ret = retentionPercent(r);
    const parts = [
      `${n(r.views)} просмотров${verdict ? ` (${VERDICT_WORD[verdict]})` : ""}`,
      `охват ${n(r.reach)}`,
      `пролистали ${pct(r.skipRate)}`,
      `смотрят ${sec(r.avgWatchTime)}${ret != null ? ` (~${Math.round(ret)}% длины)` : ""}`,
      `вовлечение ${pct(engagementRate(r))}`,
    ];
    lines.push(`- ${reelLabel(r)} — ${parts.join(", ")}`);
  }

  // Вопросы зрителей из комментариев — если человек уже собирал их в разделе
  // «Канал» (берутся из кэша, к API не ходим). Это боли словами аудитории —
  // самая честная фактура против «средних по интернету» тем.
  if (questions.length > 0) {
    lines.push(
      "",
      "О чём спрашивают зрители под его рилсами (из комментариев, их слова — не догадки):"
    );
    for (const t of questions.slice(0, 6)) {
      const ex = t.examples
        .slice(0, 2)
        .map((e) => `«${e.text.slice(0, 140)}»`)
        .join("; ");
      lines.push(`- ${t.keyword} (${t.count}×): ${ex}`);
    }
  }

  return lines.join("\n");
}

export type IgMissingReason = "none" | "expired" | "unavailable";

/**
 * Блок для Instagram-проекта, когда цифр по аккаунту НЕТ:
 *  • none        — аккаунт не подключён;
 *  • expired     — токен протух (60 дней без продления) — нужно ПЕРЕподключить;
 *  • unavailable — подключён, но снимок сейчас не получили (таймаут, сбой API).
 *
 * ⚠️ Отдельно от приглашения подключить YouTube (connectYouTubeInstruction в
 * system.ts): то зовёт подключить КАНАЛ и ставит маркер под кнопку «Подключить
 * YouTube» — на Instagram-проекте и текст, и кнопка были бы ложью. Маркера тут
 * нет: подключение — через настройки проекта, о них и говорим.
 * ⚠️ Правила площадки идут и сюда: без них модель на Instagram-проекте советует
 * CTR превью и теги — как будто это YouTube.
 */
export function instagramNotConnectedBlock(reason: IgMissingReason = "none"): string {
  const head =
    reason === "expired"
      ? [
          "# ПЛОЩАДКА ПРОЕКТА — INSTAGRAM, ДОСТУП К АККАУНТУ ИСТЁК",
          "Проект про Instagram (рилсы). Аккаунт был подключён, но доступ истёк (Instagram выдаёт его на 60 дней) — свежих цифр по рилсам у тебя нет. Не выдумывай их.",
          "Если вопрос прямо про его аккаунт, охваты, почему не заходит — скажи по-человечески, что аккаунт надо переподключить в настройках проекта, тогда разберёшь по цифрам; пока можно прислать скриншот статистики. Один раз и по делу, не в каждом ответе.",
        ]
      : reason === "unavailable"
        ? [
            "# ПЛОЩАДКА ПРОЕКТА — INSTAGRAM (статистика сейчас недоступна)",
            "Проект про Instagram (рилсы), аккаунт подключён, но цифры по нему сейчас получить не удалось. Не выдумывай их; если вопрос про его статистику — скажи, что сейчас данные не подтянулись, и предложи спросить ещё раз чуть позже или прислать скриншот.",
          ]
        : [
            "# ПЛОЩАДКА ПРОЕКТА — INSTAGRAM, АККАУНТ НЕ ПОДКЛЮЧЁН",
            "Проект про Instagram (рилсы), но аккаунт к нему не подключён — цифр по его рилсам у тебя нет. Не выдумывай их и не рассуждай так, будто видел статистику.",
            "Если вопрос прямо про его аккаунт, охваты, почему не заходит — скажи по-человечески, что для разбора по цифрам аккаунт можно подключить в настройках проекта (нужен профессиональный аккаунт — Business или Creator), и предложи пока прислать скриншот статистики. Один раз и по делу, не в каждом ответе.",
          ];
  return [
    ...head,
    "⚠️ Это Instagram, а не YouTube: советы про CTR, горизонтальные превью, теги и SEO-описание не переносятся. Упаковка рилса — хук в первые 3 секунды, вертикальная обложка под сетку профиля, подпись и текст на экране. Формулы по ВИСП работают как первая строка подписи и текст на экране.",
  ].join("\n");
}
