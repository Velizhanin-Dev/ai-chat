// Тренд к прошлому периоду: " (+12%)" / " (−4%)" / "" (нет прошлого / деление на 0 / ноль).
function snapTrend(cur: number, prev: number | null): string {
  if (prev == null || prev === 0) return "";
  const pct = Math.round(((cur - prev) / Math.abs(prev)) * 100);
  if (pct === 0) return "";
  return ` (${pct > 0 ? "+" : "−"}${Math.abs(pct)}%)`;
}

