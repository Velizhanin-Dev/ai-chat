// Единый источник правды для inline-маркеров в ответах ассистента. Сервер кладёт
// маркер в промпт-инструкцию (модель вставляет его в конец ответа, когда уместно),
// клиент вырезает маркер из текста и рисует соответствующий виджет (кнопку/CTA).
// БЕЗ серверных зависимостей — импортируется и на клиенте, и на сервере.

// Маркер «предложить подключить YouTube-канал». Модель ставит его отдельной строкой
// в самом конце ответа, когда данные канала реально нужны, а канал не подключён.
export const CONNECT_YT_MARKER = "[[connect_youtube]]";

// Вырезает маркер подключения из текста ответа и говорит, показывать ли CTA-кнопку.
// Во время стрима также срезает «хвостовой» недописанный маркер ("...\n[[connect_you"),
// чтобы он не мигал по мере набора текста.
export function splitConnectCta(content: string): { text: string; cta: boolean } {
  if (!content.includes("[[")) return { text: content, cta: false };
  const cta = content.includes(CONNECT_YT_MARKER);
  let text = content.split(CONNECT_YT_MARKER).join("");
  // Незакрытый хвост маркера во время стрима — не рендерим его как текст.
  text = text.replace(/\s*\[\[[a-z_]*$/i, "");
  if (cta) text = text.replace(/\s+$/, "");
  return { text, cta };
}
